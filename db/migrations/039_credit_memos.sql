CREATE TABLE IF NOT EXISTS acc_credit_memos (
  id char(36) NOT NULL,
  workspace_id char(36) NOT NULL,
  side varchar(2) NOT NULL,
  memo_no varchar(100) NOT NULL,
  memo_date date NOT NULL,
  invoice_id char(36) NOT NULL,
  invoice_no varchar(100) NOT NULL,
  partner_name varchar(255) NULL,
  reason text NOT NULL,
  net decimal(18,4) NOT NULL,
  vat decimal(18,4) NOT NULL DEFAULT 0,
  total decimal(18,4) NOT NULL,
  status varchar(12) NOT NULL DEFAULT 'posted',
  journal_entry_id char(36) NULL,
  reversal_journal_id char(36) NULL,
  cancellation_reason text NULL,
  posting_key char(36) NOT NULL,
  created_by char(36) NULL,
  created_at datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY uq_cm_posting_key (workspace_id, posting_key),
  UNIQUE KEY uq_cm_memo_no (workspace_id, side, memo_no),
  KEY idx_cm_invoice (workspace_id, invoice_id),
  CONSTRAINT ck_cm_side CHECK (side IN ('ar','ap')),
  CONSTRAINT ck_cm_amounts CHECK (net > 0 AND vat >= 0),
  CONSTRAINT ck_cm_status CHECK (status IN ('posted','cancelled')),
  CONSTRAINT fk_cm_workspace FOREIGN KEY (workspace_id) REFERENCES workspaces (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
